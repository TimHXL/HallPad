module envelope_scaler (

    input  wire signed [15:0] audio_in,
    input  wire        [15:0] env_level,

    output wire signed [15:0] audio_out

);

    //==================================================
    // env_level虽然是16 bit，
    // 但数值范围是0 ~ 65535，为无符号正数。
    //
    // 前面补0扩展成17-bit signed，
    // 避免65535被解释成-1。
    //==================================================
    wire signed [16:0] env_ext;

    assign env_ext =
        {1'b0, env_level};


    //==================================================
    // 16 bit × 17 bit = 33 bit
    //==================================================
    wire signed [32:0] product;

    assign product =
        $signed(audio_in) *
        $signed(env_ext);


    //==================================================
    // env_level相当于Q0.16比例系数
    //
    // 0     → 0%
    // 32768 → 50%
    // 65535 → 接近100%
    //
    // 相当于：
    //
    // product >>> 16
    //
    // 右移后有效结果为17 bit。
    //==================================================
    wire signed [16:0] scaled;

    assign scaled =
        product[32:16];


    //==================================================
    // 因为env_level最大仅为65535/65536，
    // 输出绝不会比audio_in幅度更大。
    //
    // 所以scaled[16]只是冗余符号位，
    // 显式取低16位即可。
    //==================================================
    assign audio_out =
        scaled[15:0];



endmodule